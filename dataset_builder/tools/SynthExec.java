import java.io.BufferedOutputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

import org.jacoco.core.data.ExecutionData;
import org.jacoco.core.data.ExecutionDataWriter;
import org.jacoco.core.internal.data.CRC64;
import org.jacoco.core.internal.flow.ClassProbesAdapter;
import org.jacoco.core.internal.flow.ClassProbesVisitor;
import org.jacoco.core.internal.flow.MethodProbesVisitor;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;

/**
 * Writes a JaCoCo .exec file for a set of compiled class directories, marking a
 * deterministic share of each class's probes as executed.
 *
 * Why this exists: the dataset's real .ec files come off a device, and this host
 * has no emulator (aarch64, no /dev/kvm). Without execution data a report is
 * still produced but every line is red, which cannot distinguish "the mapping is
 * correct" from "nothing matched". Writing execution data keyed by the same class
 * id the reporter computes (CRC64 of the class bytes) and sized by the same probe
 * count exercises the parts that actually break: id matching, probe-count
 * agreement, source resolution, and the green/yellow/red markup.
 *
 * This is a report-pipeline check, not a coverage measurement. The percentages it
 * produces are a property of the requested fraction, not of any test run.
 *
 * Usage: SynthExec <out.exec> <fraction 0..1> <classdir|jar> [more...]
 */
public final class SynthExec {

    /** Captures the probe count JaCoCo would allocate for one class. */
    private static final class ProbeCounter extends ClassProbesVisitor {
        int total = -1;

        @Override
        public MethodProbesVisitor visitMethod(final int access, final String name,
                final String desc, final String signature, final String[] exceptions) {
            // null makes ClassProbesAdapter use its own empty visitor; the probe
            // ids are generated by the adapter either way.
            return null;
        }

        @Override
        public void visitTotalProbeCount(final int count) {
            total = count;
        }
    }

    private static boolean[] probesFor(final byte[] bytes, final double fraction) {
        final ClassReader reader = new ClassReader(bytes);
        // Analyzer skips these two, so their ids never appear in a report and
        // including them would only add unmatched entries.
        if ((reader.getAccess() & Opcodes.ACC_MODULE) != 0) {
            return null;
        }
        if ((reader.getAccess() & Opcodes.ACC_SYNTHETIC) != 0) {
            return null;
        }
        final ProbeCounter counter = new ProbeCounter();
        reader.accept(new ClassProbesAdapter(counter, false), 0);
        if (counter.total <= 0) {
            return null;
        }
        final boolean[] probes = new boolean[counter.total];
        if (fraction >= 1.0) {
            java.util.Arrays.fill(probes, true);
            return probes;
        }
        // Deterministic and seeded per class, so a rebuilt report is comparable
        // to the previous one instead of shifting on every run.
        final java.util.Random rnd = new java.util.Random(CRC64.classId(bytes));
        for (int i = 0; i < probes.length; i++) {
            probes[i] = rnd.nextDouble() < fraction;
        }
        return probes;
    }

    public static void main(final String[] args) throws IOException {
        if (args.length < 3) {
            System.err.println("usage: SynthExec <out.exec> <fraction> <classdir|jar>...");
            System.exit(2);
        }
        final Path out = Paths.get(args[0]);
        final double fraction = Double.parseDouble(args[1]);

        final List<Path> classFiles = new ArrayList<>();
        for (int i = 2; i < args.length; i++) {
            final Path root = Paths.get(args[i]);
            if (!Files.exists(root)) {
                System.err.println("missing: " + root);
                continue;
            }
            if (Files.isRegularFile(root)) {
                classFiles.add(root);
                continue;
            }
            try (Stream<Path> walk = Files.walk(root)) {
                walk.filter(Files::isRegularFile)
                        .filter(p -> p.toString().endsWith(".class"))
                        .forEach(classFiles::add);
            }
        }

        int written = 0;
        int skipped = 0;
        long probeTotal = 0;
        if (out.getParent() != null) {
            Files.createDirectories(out.getParent());
        }
        try (OutputStream os = new BufferedOutputStream(new FileOutputStream(out.toFile()))) {
            final ExecutionDataWriter writer = new ExecutionDataWriter(os);
            for (final Path p : classFiles) {
                final byte[] bytes;
                try {
                    bytes = Files.readAllBytes(p);
                } catch (final IOException exc) {
                    skipped++;
                    continue;
                }
                final boolean[] probes;
                try {
                    probes = probesFor(bytes, fraction);
                } catch (final RuntimeException exc) {
                    // An unparseable class is a real dataset defect: the reporter
                    // would fail on it too. Count it rather than aborting.
                    skipped++;
                    continue;
                }
                if (probes == null) {
                    skipped++;
                    continue;
                }
                final ClassReader reader = new ClassReader(bytes);
                writer.visitClassExecution(new ExecutionData(CRC64.classId(bytes),
                        reader.getClassName(), probes));
                written++;
                probeTotal += probes.length;
            }
        }
        System.out.printf("classes=%d written=%d skipped=%d probes=%d%n",
                classFiles.size(), written, skipped, probeTotal);
    }
}
